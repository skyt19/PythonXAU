class SystemState(Base):
    """System state and kill switch."""

    __tablename__ = "system_state"

    id = Column(Integer, primary_key=True)
    execution_enabled = Column(Boolean, default=False, nullable=False)
    last_account_verification = Column(DateTime, nullable=True)
    verified_account_login = Column(String(100), nullable=True)
    verified_account_server = Column(String(100), nullable=True)
    session_start_equity = Column(Float, nullable=True)
    session_start_time = Column(DateTime, nullable=True)
    daily_realized_pnl = Column(Float, default=0.0, nullable=False)
    high_water_mark = Column(Float, nullable=True)
    emergency_stop_reason = Column(Text, nullable=True)
    last_updated = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)


class MarketData(Base):
    """OHLC market data."""

    __tablename__ = "market_data"

    id = Column(Integer, primary_key=True)
    symbol = Column(String(20), nullable=False, index=True)
    timeframe = Column(String(10), nullable=False)
    timestamp = Column(DateTime, nullable=False, index=True)
    open = Column(Float, nullable=False)
    high = Column(Float, nullable=False)
    low = Column(Float, nullable=False)
    close = Column(Float, nullable=False)
    tick_volume = Column(Integer, nullable=False)
    spread = Column(Float, nullable=True)
    real_volume = Column(Float, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)

    __table_args__ = (
        # Unique constraint on symbol, timeframe, timestamp
        {"sqlite_autoincrement": True},
    )


class RegimePrediction(Base):
    """LSTM regime predictions."""

    __tablename__ = "regime_predictions"

    id = Column(Integer, primary_key=True)
    timestamp = Column(DateTime, nullable=False, index=True)
    model_version = Column(String(50), nullable=False)
    regime = Column(Enum(RegimeType), nullable=False)
    prob_trend = Column(Float, nullable=False)
    prob_range = Column(Float, nullable=False)
    prob_high_vol = Column(Float, nullable=False)
    confidence = Column(Float, nullable=False)
    features_snapshot = Column(JSON, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)


class Signal(Base):
    """Trading signals generated by strategy."""

    __tablename__ = "signals"

    id = Column(Integer, primary_key=True)
    timestamp = Column(DateTime, nullable=False, index=True)
    regime_prediction_id = Column(Integer, ForeignKey("regime_predictions.id"))
    direction = Column(Enum(TradeDirection), nullable=False)
    entry_price = Column(Float, nullable=False)
    stop_loss = Column(Float, nullable=False)
    take_profit = Column(Float, nullable=False)
    risk_amount = Column(Float, nullable=False)
    volume = Column(Float, nullable=False)
    ai_approved = Column(Boolean, nullable=False)
    rejection_reason = Column(Text, nullable=True)
    strategy_reason = Column(Text, nullable=True)
    indicators_snapshot = Column(JSON, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)

    regime_prediction = relationship("RegimePrediction", backref="signals")


class Trade(Base):
    """Executed trades and their outcomes."""

    __tablename__ = "trades"

    id = Column(Integer, primary_key=True)
    signal_id = Column(Integer, ForeignKey("signals.id"), nullable=True)
    broker_order_id = Column(String(50), nullable=True, unique=True)

    # Entry
    entry_timestamp = Column(DateTime, nullable=False, index=True)
    direction = Column(Enum(TradeDirection), nullable=False)
    entry_price_expected = Column(Float, nullable=False)
    entry_price_actual = Column(Float, nullable=True)
    volume = Column(Float, nullable=False)
    entry_spread = Column(Float, nullable=True)
    entry_commission = Column(Float, nullable=True)

    # Exit
    exit_timestamp = Column(DateTime, nullable=True)
    exit_price_expected = Column(Float, nullable=True)
    exit_price_actual = Column(Float, nullable=True)
    exit_reason = Column(Enum(ExitReason), nullable=True)

    # Risk management
    stop_loss = Column(Float, nullable=False)
    take_profit = Column(Float, nullable=False)
    stop_moved_count = Column(Integer, default=0)

    # Outcome
    realized_pnl = Column(Float, nullable=True)
    realized_pnl_pct = Column(Float, nullable=True)
    r_multiple = Column(Float, nullable=True)
    max_favorable_excursion = Column(Float, nullable=True)
    max_adverse_excursion = Column(Float, nullable=True)
    holding_bars = Column(Integer, nullable=True)

    # Costs
    total_commission = Column(Float, nullable=True)
    total_swap = Column(Float, nullable=True)
    entry_slippage = Column(Float, nullable=True)
    exit_slippage = Column(Float, nullable=True)

    # Analysis
    error_category = Column(Enum(ErrorCategory), nullable=True)
    error_analysis = Column(Text, nullable=True)

    # Status
    status = Column(Enum(OrderStatus), default=OrderStatus.PENDING)
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    signal = relationship("Signal", backref="trades")


